# @brief    Generate the BrainFlow board layouts that streaming_board:// knows without BrainFlow.
"""Generate ``src/libraries/acq/devices/brainflow/brainflow_boards.inc``.

The receiver of BrainFlow's multicast streamer needs the row layout of the board behind the stream. With BrainFlow
installed it asks BrainFlow; the boards listed here it knows without. Run with BrainFlow installed
(``pip install brainflow``); ``--check`` fails when the committed file differs.
"""

import argparse
import json
import sys
from pathlib import Path

BOARDS = (-1, 0, 1, 2)  # synthetic, Cyton, Ganglion, Cyton + Daisy
OUTPUT = Path(__file__).resolve().parents[2] / "src/libraries/acq/devices/brainflow/brainflow_boards.inc"


def generate():
    import brainflow
    from brainflow.board_shim import BoardShim

    version = getattr(brainflow, "__version__", None)
    if not version:
        from importlib.metadata import version as package_version

        version = package_version("brainflow")
    lines = [
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// Copyright (c) 2026 MNE-CPP Authors",
        f"// Generated by scripts/acq/generate_brainflow_boards.py from BrainFlow {version}; do not edit.",
        "// The descriptions are BrainFlow's (brainflow_boards.cpp, MIT license, Copyright (c) 2018 Andrey Parfenov).",
    ]
    for board in BOARDS:
        description = json.dumps(BoardShim.get_board_descr(board), separators=(",", ":"))
        lines.append(f'{{{board}, R"json({description})json"}},')
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file is out of date")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUTPUT.read_text() != text:
            print(f"FAIL: {OUTPUT} is out of date; run {Path(__file__).name}")
            return 1
        print(f"PASS: {OUTPUT.name} is current")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
